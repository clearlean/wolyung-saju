function bucketByCount(count: number): 'none' | 'low' | 'balanced' | 'high' {
  if (count === 0) {
    return 'none';
  }

  if (count === 1) {
    return 'low';
  }

  return count >= 4 ? 'high' : 'balanced';
}

/** 오늘 기준의 사주 연도. 입춘 전이면 전년도로 본다. */
export function currentSajuYear(now: Date = new Date()): number {
  const gregorianYear = now.getUTCFullYear();
  return now < findStartOfSpring(gregorianYear)
    ? gregorianYear - 1
    : gregorianYear;
}

export function buildLoveReading(
  chart: SajuChart,
  name: string,
  now: Date = new Date(),
): LoveTopic[] {
  const displayName = name.trim() || '그대';
  const dayStemName = `${STEMS[chart.dayStem]}${STEM_READINGS[chart.dayStem]}`;
  const nature = DAY_STEM_NATURE[chart.dayStem];
  const palace = SPOUSE_PALACE[chart.daySpouseBranch];
  const spouseBranch = BRANCHES[chart.daySpouseBranch];

  const expressionKey = bucketByCount(chart.tenGodGroupCounts.식상);
  const spouseKey = bucketByCount(chart.spouseStarCount);

  const tensionKey = chart.spousePalaceClashed
    ? 'clash'
    : chart.elementCounts[chart.dominantElement] >= 4
      ? 'excess'
      : chart.missingElements.length >= 2
        ? 'lack'
        : 'steady';

  const signalKey =
    chart.hasPeachBlossom && chart.hasRedCharm
      ? 'both'
      : chart.hasPeachBlossom
        ? 'peach'
        : chart.hasRedCharm
          ? 'charm'
          : 'quiet';

  const isBalanced =
    chart.elementCounts[chart.dominantElement] <= 2 &&
    chart.missingElements.length === 0;
  const temperatureKey: Element | '균형' = isBalanced
    ? '균형'
    : chart.dominantElement;

  const sajuYear = currentSajuYear(now);
  const yearGanji = sexagenaryOfYear(sajuYear);
  const yearTenGod = tenGodOf(chart.dayStem, yearGanji.stem);
  const yearLabel = `${STEMS[yearGanji.stem]}${BRANCHES[yearGanji.branch]}`;

  const totalCharacters = chart.hourPillar ? 8 : 6;
  const dominantCount = chart.elementCounts[chart.dominantElement];
  const spouseStarLabel = chart.spouseStar;
  const starNames = [
    chart.hasPeachBlossom ? '도화살' : null,
    chart.hasRedCharm ? '홍염살' : null,
    chart.hasTravelStar ? '역마살' : null,
  ].filter((value): value is string => value !== null);

  return [
    {
      id: 'nature',
      title: '연애의 바탕',
      teaser: nature.teaser,
      basis: `일간 ${dayStemName} · ${nature.image}`,
      body: [
        `${displayName} 님의 일간은 ${dayStemName}, ${nature.image}의 기운입니다.`,
        ...nature.lines,
      ],
    },
    {
      id: 'attraction',
      title: '끌리는 사람의 결',
      teaser: palace.teaser,
      basis: `일지 ${spouseBranch} · 배우자궁`,
      body: [
        ...palace.lines,
        `일지는 평생 곁에 둘 사람이 앉는 자리입니다. ${spouseBranch}의 결을 가진 사람 앞에서 유독 편안했다면, 그건 우연이 아닙니다.`,
      ],
    },
    {
      id: 'expression',
      title: '마음을 표현하는 방식',
      teaser: EXPRESSION[expressionKey].teaser,
      basis: `식상 ${chart.tenGodGroupCounts.식상}개`,
      body: [...EXPRESSION[expressionKey].lines],
    },
    {
      id: 'spouse-star',
      title: '인연이 들어오는 자리',
      teaser: SPOUSE_STAR[spouseKey].teaser,
      basis: `${spouseStarLabel} ${chart.spouseStarCount}개 · ${
        chart.input.gender === 'male' ? '남명' : '여명'
      }`,
      body: [...SPOUSE_STAR[spouseKey].lines],
    },
    {
      id: 'tension',
      title: '사랑이 흔들리는 지점',
      teaser: TENSION[tensionKey].teaser,
      basis:
        tensionKey === 'clash'
          ? `일지 ${spouseBranch} 충`
          : tensionKey === 'excess'
            ? `${chart.dominantElement}(${ELEMENT_HANJA[chart.dominantElement]}) ${dominantCount}개`
            : tensionKey === 'lack'
              ? `없는 오행 ${chart.missingElements.join('·')}`
              : '오행 안정',
      body: [...TENSION[tensionKey].lines],
    },
    {
      id: 'signal',
      title: '인연이 다가오는 방식',
      teaser: SIGNAL[signalKey].teaser,
      basis: starNames.length > 0 ? starNames.join(' · ') : '드러난 살 없음',
      body: chart.hasTravelStar
        ? [
            ...SIGNAL[signalKey].lines,
            '여기에 역마살이 함께 들었습니다. 사는 곳을 옮기거나 멀리 다녀오는 길 위에서 인연이 시작되는 사주이니, 익숙한 반경 밖으로 나가 보세요.',
          ]
        : [...SIGNAL[signalKey].lines],
    },
    {
      id: 'temperature',
      title: '관계의 온도',
      teaser: TEMPERATURE[temperatureKey].teaser,
      basis: isBalanced
        ? '오행 균형'
        : `${chart.dominantElement}(${ELEMENT_HANJA[chart.dominantElement]}) ${dominantCount}/${totalCharacters}`,
      body: [...TEMPERATURE[temperatureKey].lines],
    },
    {
      id: 'this-year',
      title: `${sajuYear}년의 연애 흐름`,
      teaser: YEARLY[yearTenGod].teaser,
      basis: `${yearLabel}년 · ${yearTenGod}`,
      body: [
        `${sajuYear}년은 ${yearLabel}년, 일간 ${STEMS[chart.dayStem]}에게는 ${yearTenGod}에 해당하는 해입니다.`,
        ...YEARLY[yearTenGod].lines,
      ],
    },
  ];
}
